// White card with a quiet zone of 2 modules; dark modules drawn as one SVG path so edges stay crisp.
export const Qr: React.FC<{size: number; rows: string[]}> = ({size, rows}) => {
  const n = rows.length + 4;
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '1') d += `M${x + 2} ${y + 2}h1v1h-1z`;
  });
  return (
    <svg width={size} height={size} viewBox={`0 0 ${n} ${n}`} shapeRendering="crispEdges" style={{display: 'block', borderRadius: 8}}>
      <rect width={n} height={n} fill="#fff" />
      <path d={d} fill="#111" />
    </svg>
  );
};
